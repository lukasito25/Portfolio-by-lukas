/**
 * Asserts that a generated document identifies nobody but its author.
 *
 * These files go to employers under Lukáš's name. An audit found them already
 * clean — no tool fingerprint, no model name, no hidden characters — but a
 * finding is only worth as much as the thing that keeps it true. A dependency
 * bump, a new image pipeline, or one `docProps/app.xml` added for tidiness
 * would each undo it silently.
 *
 * Three separate classes of problem are checked, because they arrive by
 * different routes:
 *
 *   1. **Tool and model fingerprints.** Names of the software that produced
 *      the file, or of the model that wrote the text.
 *   2. **Hidden characters.** Zero-width spaces, bidi controls and the
 *      U+E0000–U+E007F tag range — the canonical way text is watermarked,
 *      since a whole message can be encoded in characters no renderer shows.
 *      `src/lib/ai/sanitize.ts` strips these from model output; this checks the
 *      artefact rather than trusting the pipeline.
 *   3. **Homoglyphs.** Cyrillic and Greek letters that look Latin. Worse than
 *      invisible: a recruiter searching for "Product" would not find it.
 *
 * Run: node scripts/check-doc-clean.mjs [previewDir]
 */

import { readFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'
import PizZip from 'pizzip'

const dir = process.argv[2] ?? 'doc-previews'

/**
 * Words that must never appear.
 *
 * Short tokens are word-bounded, and that is not fussiness: an unanchored
 * `llm` matches the `llM` inside `w:tblCellMar`, and an unanchored `AI` would
 * match "Vertex AI", a real skill on the CV. A check that cries wolf gets
 * switched off, which is worse than not having it.
 */
const FINGERPRINTS =
  /claude|anthropic|\bsonnet\b|\bopus\b|gemini|openai|chatgpt|\bgpt-?\d|\bllm\b|docxtemplater|pizzip|libvips|generated by|co-authored|language model/i

/**
 * Codepoints with no honest business in a document.
 *
 * Deliberately wider than `src/lib/ai/sanitize.ts`. That file strips what a
 * model might emit; this one asks what could be hiding in a finished artefact,
 * and the two variation-selector blocks belong in the second list —
 * U+FE00–U+FE0F and U+E0100–U+E01EF render as nothing and can carry a payload
 * exactly as the tag block can. Both were found by a negative control that this
 * check passed when it should have failed. Escapes rather than literals here
 * on purpose: a regex of invisible characters is unreadable and unreviewable
 * when written as the characters themselves.
 */
const INVISIBLE =
  /[\u00ad\u200b-\u200f\u202a-\u202e\u2060-\u2064\u2066-\u2069\ufe00-\ufe0f\ufeff\ufff9-\ufffb]|[\u{E0000}-\u{E007F}]|[\u{E0100}-\u{E01EF}]/u

/** Cyrillic and Greek letters that are visually identical to Latin ones. */
const HOMOGLYPH = /[Ѐ-ӿͰ-Ͽ]/u

const fail = []
const note = m => console.log(`  ${m}`)

const files = readdirSync(dir).filter(f => f.endsWith('.docx'))
if (!files.length) {
  console.error(
    `No .docx in ${dir}/. Run: npx tsx scripts/preview-doc-variants.ts ${dir}`
  )
  process.exit(1)
}

console.log(`\nchecking ${files.length} documents in ${dir}/\n`)

for (const file of files) {
  const buf = readFileSync(join(dir, file))
  const zip = new PizZip(buf)
  const names = Object.keys(zip.files).filter(n => !n.endsWith('/'))
  const problems = []

  /* 1. Fingerprints, in the XML and in the raw bytes.
   *
   * The raw scan matters independently: a string could sit in a zip comment,
   * an extra field, or a part this loop does not decode. */
  for (const name of names.filter(n => n.endsWith('.xml'))) {
    const text = zip.file(name).asText()
    const hit = text.match(FINGERPRINTS)
    if (hit) problems.push(`fingerprint "${hit[0]}" in ${name}`)
  }
  const rawHit = buf.toString('latin1').match(FINGERPRINTS)
  if (rawHit) problems.push(`fingerprint "${rawHit[0]}" in the raw bytes`)

  /* 2 & 3. Hidden characters and homoglyphs, in the document text only —
   * binary parts legitimately contain arbitrary bytes. */
  for (const name of names.filter(n => n.endsWith('.xml'))) {
    for (const m of zip
      .file(name)
      .asText()
      .matchAll(/<w:t[^>]*>([^<]*)<\/w:t>/g)) {
      if (INVISIBLE.test(m[1])) {
        problems.push(
          `hidden character in ${name}: ${JSON.stringify(m[1].slice(0, 40))}`
        )
      }
      if (HOMOGLYPH.test(m[1])) {
        problems.push(
          `homoglyph in ${name}: ${JSON.stringify(m[1].slice(0, 40))}`
        )
      }
    }
  }

  /* 4. Metadata. `app.xml` is the part that would claim Word produced this. */
  if (names.includes('docProps/app.xml')) {
    problems.push(
      'docProps/app.xml present — it declares a producing application'
    )
  }
  if (!names.includes('docProps/core.xml')) {
    problems.push(
      'no docProps/core.xml — a document with no author at all is itself unusual'
    )
  } else {
    const core = zip.file('docProps/core.xml').asText()
    const creator = core.match(/<dc:creator>([^<]*)<\/dc:creator>/)?.[1] ?? ''
    if (!creator.trim()) problems.push('dc:creator is empty')
    // The templates ship with it blank; only rendered documents carry a name.
    else if (!/Hošala/.test(creator)) {
      problems.push(`dc:creator is "${creator}", which is not the author`)
    }
  }

  /* 5. Image metadata. PNG text chunks are a standard place for a tool name. */
  for (const name of names.filter(n => n.endsWith('.png'))) {
    const png = zip.file(name).asNodeBuffer().toString('latin1')
    for (const chunk of ['tEXt', 'iTXt', 'zTXt', 'eXIf']) {
      if (png.includes(chunk)) problems.push(`${name} carries a ${chunk} chunk`)
    }
  }

  /* 6. Zip-level surfaces: an archive comment is invisible to every reader. */
  const eocd = buf.lastIndexOf(Buffer.from([0x50, 0x4b, 0x05, 0x06]))
  if (eocd >= 0 && buf.readUInt16LE(eocd + 20) !== 0) {
    problems.push('the zip has an archive comment')
  }

  if (problems.length) {
    fail.push(`${file}: ${problems.length} problem(s)`)
    note(`✗ ${file}`)
    problems.forEach(p => note(`    ${p}`))
  } else {
    note(`✓ ${file}`)
  }
}

if (fail.length) {
  console.error(`\n${fail.length} file(s) failed:`)
  fail.forEach(f => console.error(`  - ${f}`))
  process.exit(1)
}
console.log('\nno tool fingerprints, hidden characters or homoglyphs\n')
