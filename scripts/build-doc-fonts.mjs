/**
 * Prepares the typefaces the generated documents are set in.
 *
 * The documents were set in Calibri because "the site's Geist and Space Grotesk
 * are not on a recruiter's machine". That reasoning was sound for a document
 * that only *names* a font and hopes it is installed — but both a `.docx` and a
 * PDF can carry the font with them, so the constraint was never real. Calibri
 * is the Microsoft default, and a default typeface is the loudest signal that a
 * document came out of a word processor rather than a studio.
 *
 * Source and licence: Geist Sans, from the `geist` npm package, which ships
 * static TTFs directly. SIL Open Font License 1.1 — Vercel / basement.studio.
 * OFL clause 1 requires the licence to travel with the font, so the licence
 * text is copied next to the output. Embedding is explicitly permitted; what
 * the OFL forbids is selling the font on its own.
 *
 * `scripts/doc-fonts.mjs` explains why Space Grotesk, the site's display face,
 * is not here.
 *
 * Why subset: a full Geist weight is ~124 KB, so two weights would put a
 * quarter of a megabyte of font into every email attachment. Subsetting to the
 * characters a CV in English, Italian, German or Slovak can actually contain
 * roughly halves it, with no visible difference.
 *
 * Run: node scripts/build-doc-fonts.mjs
 */

import { mkdirSync, writeFileSync, readFileSync, copyFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import subsetFont from 'subset-font'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'templates', 'fonts')

/**
 * The glyph set to keep.
 *
 * Latin Extended-A is not optional: "Lukáš Hošala" needs it, and so do the
 * Italian and German editions. The punctuation block is exactly what the
 * templates and the house style emit — en dashes in date ranges, the middot
 * separator, the euro sign, curly quotes — and a missing glyph in a document
 * is a hollow box in front of a recruiter.
 */
const CHARSET = [
  // ASCII printable
  ...Array.from({ length: 0x7e - 0x20 + 1 }, (_, i) => 0x20 + i),
  // Latin-1 Supplement — accented vowels for IT/DE/FR company names
  ...Array.from({ length: 0xff - 0xa0 + 1 }, (_, i) => 0xa0 + i),
  // Latin Extended-A — Slovak, Czech, Polish, Hungarian diacritics
  ...Array.from({ length: 0x17f - 0x100 + 1 }, (_, i) => 0x100 + i),
]
  .map(c => String.fromCodePoint(c))
  .join('')
  // Punctuation, currency and marks used by the templates and the house style.
  .concat('‐‑‒–—―‘’‚“”„†‡•‰′″‹›€₤₹←→↑↓↔✓✗✔✕°±×÷≈≠≤≥№™©®…⁄')

const geist = name =>
  join(root, 'node_modules/geist/dist/fonts/geist-sans', name)

const targets = [
  { file: 'Geist-Regular.ttf', from: geist('Geist-Regular.ttf') },
  // The bold instance. SemiBold rather than Bold is deliberate: the bullet
  // lead-in labels are set in it and repeat down the whole page, and true Bold
  // at 10.5pt turns that column into a row of black bars.
  { file: 'Geist-SemiBold.ttf', from: geist('Geist-SemiBold.ttf') },
  // The two heavier weights are for the PDF `column` design only, which sets
  // the name in the heaviest cut the way its reference does. The .docx
  // templates embed just the two above — `scripts/doc-fonts.mjs` names its own
  // files — so these add nothing to an attachment.
  { file: 'Geist-Bold.ttf', from: geist('Geist-Bold.ttf') },
  { file: 'Geist-Black.ttf', from: geist('Geist-Black.ttf') },
]

mkdirSync(outDir, { recursive: true })

let total = 0
for (const target of targets) {
  const source = readFileSync(target.from)
  const subset = await subsetFont(source, CHARSET, { targetFormat: 'truetype' })

  writeFileSync(join(outDir, target.file), subset)
  total += subset.length
  console.log(
    `${target.file.padEnd(24)} ${(source.length / 1024).toFixed(1).padStart(7)} KB → ${(subset.length / 1024).toFixed(1).padStart(6)} KB`
  )
}

/* OFL 1.1 requires the licence to travel with the font. */
copyFileSync(
  join(root, 'node_modules/geist/LICENSE.txt'),
  join(outDir, 'Geist-OFL.txt')
)

writeFileSync(
  join(outDir, 'README.md'),
  `# Document typefaces

Generated by \`node scripts/build-doc-fonts.mjs\`. Do not edit by hand.

Subsets of Geist Sans (Vercel / basement.studio) under the SIL Open Font
License 1.1 — see \`Geist-OFL.txt\`, which the licence requires to travel with
the font. See \`scripts/doc-fonts.mjs\` for why Space Grotesk is not here.

They live under \`templates/\` rather than a folder of their own for one
practical reason: \`src/lib/documents/render.ts\` already reads that directory
at runtime via \`process.cwd()\` and it is known to survive the Vercel
standalone build. A new top-level directory would have to prove that again.
`
)

console.log(`\ntotal embedded weight: ${(total / 1024).toFixed(1)} KB`)
